import { createRequire } from "node:module";
import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";

const requireFromProject = createRequire(
  join(process.cwd(), "scripts", "_license-resolver.cjs"),
);

/**
 * The extension bundles its runtime dependencies with esbuild and packages
 * with `vsce --no-dependencies`. Generate one shipped notice containing the
 * license texts for every production package reachable from package.json.
 */
export async function writeThirdPartyNotices(
  outputPath = join(process.cwd(), "dist", "THIRD_PARTY_NOTICES.txt"),
) {
  const rootPackage = JSON.parse(
    await readFile(join(process.cwd(), "package.json"), "utf8"),
  );
  const visited = new Set();
  const packages = [];

  async function visitPackage(packageJsonPath) {
    const packageDirectory = dirname(packageJsonPath);
    const packageRealPath = packageJsonPath;
    if (visited.has(packageRealPath)) return;
    visited.add(packageRealPath);
    const packageJson = JSON.parse(await readFile(packageJsonPath, "utf8"));
    packages.push({ packageDirectory, packageJson });
    for (const dependency of Object.keys(packageJson.dependencies ?? {})) {
      let dependencyJsonPath;
      try {
        dependencyJsonPath = resolvePackageJson(dependency, packageDirectory);
      } catch {
        // Optional platform dependencies may be absent. They are not part of
        // the generated bundle when esbuild cannot resolve them either.
        continue;
      }
      await visitPackage(dependencyJsonPath);
    }
  }

  const rootDependencies = Object.keys(rootPackage.dependencies ?? {});
  for (const dependency of rootDependencies) {
    const packageJsonPath = resolvePackageJson(dependency, process.cwd());
    await visitPackage(packageJsonPath);
  }

  packages.sort((left, right) =>
    String(left.packageJson.name).localeCompare(String(right.packageJson.name)),
  );
  const sections = [
    "Markdown Weaver third-party notices",
    "Generated by scripts/third-party-notices.mjs during npm run build.",
    "The extension bundles these production dependencies; they are listed here so the packaged VSIX retains their license texts.",
    "",
  ];
  for (const { packageDirectory, packageJson } of packages) {
    sections.push(
      `======================================================================`,
      `${packageJson.name ?? "(unnamed package)"} ${packageJson.version ?? "(unknown version)"}`,
      `License: ${formatLicense(packageJson.license)}`,
      `Package: ${relative(process.cwd(), packageDirectory)}`,
      `======================================================================`,
    );
    const files = await findNoticeFiles(packageDirectory);
    if (files.length === 0) {
      sections.push(
        "No license file was found in this package; the license identifier from package.json is retained above.",
      );
    } else {
      for (const file of files) {
        sections.push(`--- ${file.name} ---`, file.contents.trimEnd());
      }
    }
    sections.push("");
  }
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, `${sections.join("\n")}\n`, "utf8");
  return outputPath;
}

async function findNoticeFiles(packageDirectory) {
  const candidates = [
    "LICENSE",
    "LICENSE.md",
    "LICENSE.txt",
    "LICENCE",
    "LICENCE.md",
    "LICENCE.txt",
    "LICENSE-MIT.txt",
    "THIRD-PARTY-LICENSES",
    "THIRD-PARTY-LICENSES.md",
    "THIRD-PARTY-NOTICES",
    "THIRD-PARTY-NOTICES.md",
  ];
  const files = [];
  for (const name of candidates) {
    try {
      files.push({
        name,
        contents: await readFile(join(packageDirectory, name), "utf8"),
      });
    } catch {
      // Continue through aliases; packages often use LICENSE.txt instead of
      // LICENSE and Prettier ships a separate third-party notice file.
    }
  }
  return files;
}

function formatLicense(value) {
  if (typeof value === "string") return value;
  if (Array.isArray(value)) return value.join(", ");
  if (value && typeof value === "object")
    return String(value.type ?? value.name ?? "unknown");
  return "unknown";
}

function resolvePackageJson(packageName, fromDirectory) {
  const entryPoint = requireFromProject.resolve(packageName, {
    paths: [fromDirectory],
  });
  let directory = dirname(entryPoint);
  while (directory !== dirname(directory)) {
    const candidate = join(directory, "package.json");
    if (existsSync(candidate)) return candidate;
    directory = dirname(directory);
  }
  throw new Error(`Could not locate package.json for ${packageName}`);
}

if (import.meta.url === `file://${process.argv[1]}`)
  await writeThirdPartyNotices();
